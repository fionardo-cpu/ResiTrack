_PIXMAP_CACHE: dict[tuple[str, str, int, int], QPixmap] = {}
_ICON_CACHE: dict[tuple[str, str, int], QIcon] = {}


def clear_cache() -> None:
    """Release cached Qt QPixmap/QIcon instances cleanly before QApplication teardown."""
    _ICON_CACHE.clear()
    _PIXMAP_CACHE.clear()


def svg_pixmap(name: str, color: str, size: int = 16, dpr: int = 2) -> QPixmap:
    """Render a named monochrome stroke SVG icon at `size` logical px with `dpr` supersampling."""
    key = (name, color.lower(), size, dpr)
    cached = _PIXMAP_CACHE.get(key)
    if cached is not None:
        return cached

    inner = _ICON_PATHS.get(name, _ICON_PATHS["package"])
    svg_xml = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="1.8" '
        f'stroke-linecap="round" stroke-linejoin="round">{inner}</svg>'
    )
    px = size * dpr
    pm = QPixmap(px, px)
    pm.fill(Qt.transparent)
    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.Antialiasing)
    painter.setRenderHint(QPainter.SmoothPixmapTransform)
    renderer.render(painter, QRectF(0, 0, px, px))
    painter.end()
    pm.setDevicePixelRatio(float(dpr))
    _PIXMAP_CACHE[key] = pm
    return pm


def svg_icon(name: str, color: str, size: int = 16) -> QIcon:
    """Return a cached HiDPI QIcon for the requested icon name and color."""
    key = (name, color.lower(), size)
    cached = _ICON_CACHE.get(key)
    if cached is not None:
        return cached

    icon = QIcon()
    icon.addPixmap(svg_pixmap(name, color, size, dpr=1))
    icon.addPixmap(svg_pixmap(name, color, size, dpr=2))
    _ICON_CACHE[key] = icon
    return icon
